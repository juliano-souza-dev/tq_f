export function fashionFor(profile){return FASHION_CATALOG[profile?.avatar?.id]||FASHION_CATALOG.luna;}
export function fashionStatus(profile,item){
 const owned=item.id==='original'||Boolean(profile?.fashionOwned?.includes(item.id));
 const equipped=(profile?.avatar?.skinId||'original')===item.id;
 const buyable=Array.isArray(item.sources)&&item.sources.includes('coins');
 const price=Number(item.price)||0;
 return {owned,equipped,buyable,price,affordable:Number(profile?.coins||0)>=price};
}
export function acquireFashion(profile,id){
 const item=fashionFor(profile).find(s=>s.id===id);
 if(!item)return {ok:false,reason:'not-found'};
 const status=fashionStatus(profile,item);
 if(status.equipped)return {ok:true,reason:'already-equipped'};
 if(!status.owned){
  if(!status.buyable)return {ok:false,reason:'reward-only'};
  if(!status.affordable)return {ok:false,reason:'insufficient-coins',missing:status.price-Number(profile.coins||0)};
  profile.coins-=status.price;
  if(!Array.isArray(profile.fashionOwned))profile.fashionOwned=['original'];
  if(!profile.fashionOwned.includes(id))profile.fashionOwned.push(id);
 }
 profile.avatar.skinId=id;
 return {ok:true,reason:status.owned?'equipped':'purchased',spent:status.owned?0:status.price};
}
